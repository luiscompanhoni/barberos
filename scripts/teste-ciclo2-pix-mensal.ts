/** Emissão de Pix com gateway falso e banco descartável; proíbe rede. */
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";

const url = new URL(process.env.DATABASE_URL ?? "http://invalid");
if (url.hostname !== "127.0.0.1" || url.port !== "55439" || url.pathname !== "/barberos_ciclo2_review_20261103") throw new Error("Use apenas o banco descartável de revisão.");
process.env.AMBIENTE = "teste";
process.env.PAGAMENTOS_PROVIDER = "pagarme";
process.env.PAGARME_SECRET_KEY = "sk_test_falsa";
process.env.WHATSAPP_PROVIDER = "simulador";
globalThis.fetch = async () => { throw new Error("Rede bloqueada no teste"); };

async function main() {
  const { db } = await import("@/lib/db");
  const { _usarFetch } = await import("@/lib/pagamentos/pagarme");
  const { gerarPixDoMes, renovarPixSeExpirado } = await import("@/lib/assinaturas/cartao-pix");
  const { assinar, cancelar } = await import("@/lib/assinaturas/servico");
  const { aceitarDesconto, pausar, cancelarPeloCliente } = await import("@/lib/assinaturas/retencao");
  const tag = randomUUID();
  let pedidos = 0, timeout = false, liberar!: () => void, iniciou!: () => void;
  let espera: Promise<void> | null = null, iniciado: Promise<void> | null = null;
  _usarFetch((async (endereco: string, init?: RequestInit) => {
    const caminho = new URL(endereco).pathname;
    if (caminho.endsWith("/customers")) return new Response(JSON.stringify({ id: `cus_${tag}` }), { status: 200 });
    if (!caminho.endsWith("/orders") || init?.method !== "POST") throw new Error("Somente gateway falso permitido");
    pedidos++;
    if (iniciou) iniciou();
    if (espera) await espera;
    if (timeout) throw new Error("timeout fictício após possível aceitação");
    return new Response(JSON.stringify({ id: `or_${tag}_${pedidos}`, charges: [{ id: `ch_${tag}_${pedidos}`, amount: 10000, status: "pending", payment_method: "pix", created_at: "2031-04-01T00:00:00Z", last_transaction: { qr_code: "teste", expires_at: "2099-01-01T00:00:00Z" } }] }), { status: 200 });
  }) as typeof fetch);
  const cliente = await db.cliente.create({ data: { nome: "Teste", telefone: tag, email: "teste@example.invalid" } });
  const plano = await db.plano.create({ data: { nome: "Teste", precoCentavos: 10000 } });
  const a = await db.assinatura.create({ data: { clienteId: cliente.id, planoId: plano.id, gatewayId: `pixrec_${tag}`, gatewayClienteId: `cus_${tag}`, status: "ATIVA", formaPagamento: "PIX", precoCentavos: 10000, origem: "SITE" } });
  iniciado = new Promise<void>((r) => { iniciou = r; });
  espera = new Promise<void>((r) => { liberar = r; });
  const primeiro = gerarPixDoMes(a.id, "2031-04-01");
  await iniciado;
  const concorrentes = await Promise.allSettled(Array.from({ length: 3 }, () => gerarPixDoMes(a.id, "2031-04-01")));
  assert(concorrentes.every((r) => r.status === "rejected"));
  assert.equal(pedidos, 1);
  liberar(); const c = await primeiro;
  espera = null; iniciou = () => {};
  assert.equal((await gerarPixDoMes(a.id, "2031-04-01")).id, c.id);
  assert.equal(pedidos, 1);
  const seguinte = await gerarPixDoMes(a.id, "2031-05-01");
  assert.notEqual(seguinte.id, c.id); assert.equal(pedidos, 2);
  const legada = await db.cobranca.create({ data: { assinaturaId: a.id, gatewayId: `legado_${tag}`, valorCentavos: 10000, vencimento: new Date("2031-06-01T00:00:00Z"), forma: "PIX", status: "PENDENTE" } });
  assert.equal((await gerarPixDoMes(a.id, "2031-06-01")).id, legada.id); assert.equal(pedidos, 2);
  await db.assinatura.update({ where: { id: a.id }, data: { proximoVencimento: new Date("2031-06-01T00:00:00Z") } });
  await assert.rejects(() => aceitarDesconto({ assinaturaId: a.id, motivo: "PRECO", origem: "SITE" }), /Há Pix em aberto/);
  assert.equal((await db.assinatura.findUniqueOrThrow({ where: { id: a.id } })).descontoRetencaoPct, null);
  assert.equal((await db.cobranca.findUniqueOrThrow({ where: { id: legada.id } })).status, "PENDENTE");
  const clienteCorrida = await db.cliente.create({ data: { nome: "Teste corrida", telefone: `${tag}-corrida`, email: "corrida@example.invalid" } });
  const aCorrida = await db.assinatura.create({ data: { clienteId: clienteCorrida.id, planoId: plano.id, gatewayId: `pixrec_${tag}-corrida`, gatewayClienteId: `cus_${tag}-corrida`, status: "ATIVA", formaPagamento: "PIX", precoCentavos: 10000, origem: "SITE", proximoVencimento: new Date("2032-08-01T00:00:00Z") } });
  iniciado = new Promise<void>((r) => { iniciou = r; });
  espera = new Promise<void>((r) => { liberar = r; });
  const emissaoCorrida = gerarPixDoMes(aCorrida.id, "2032-08-01");
  await iniciado;
  await assert.rejects(() => aceitarDesconto({ assinaturaId: aCorrida.id, motivo: "PRECO", origem: "SITE" }), /Há Pix em aberto ou em verificação/);
  await assert.rejects(() => pausar({ assinaturaId: aCorrida.id, motivo: "VIAGEM", origem: "SITE", dias: 30 }), /Há Pix em aberto ou em verificação/);
  await assert.rejects(() => cancelar(aCorrida.id, "Teste", null), /Há Pix em aberto ou em verificação/);
  await assert.rejects(() => cancelarPeloCliente({ assinaturaId: aCorrida.id, motivo: "OUTRO", origem: "SITE" }), /Há Pix em aberto ou em verificação/);
  assert.equal((await db.assinatura.findUniqueOrThrow({ where: { id: aCorrida.id } })).descontoRetencaoPct, null);
  assert.equal((await db.assinatura.findUniqueOrThrow({ where: { id: aCorrida.id } })).pausadaEm, null);
  liberar(); await emissaoCorrida;
  espera = null; iniciou = () => {};
  await db.cobranca.update({ where: { id: legada.id }, data: { expiraEm: new Date("2000-01-01") } });
  await assert.rejects(() => renovarPixSeExpirado(legada.id));
  assert.equal((await db.cobranca.findUniqueOrThrow({ where: { id: legada.id } })).status, "PENDENTE");
  timeout = true;
  await assert.rejects(() => gerarPixDoMes(a.id, "2031-07-01"));
  assert.equal(pedidos, 4);
  await assert.rejects(() => gerarPixDoMes(a.id, "2031-07-01"));
  assert.equal(pedidos, 4);
  assert.equal((await db.emissaoPixMensal.findUniqueOrThrow({ where: { assinaturaId_vencimento: { assinaturaId: a.id, vencimento: new Date("2031-07-01T00:00:00Z") } } })).estado, "INCERTA");
  const clienteNovo = await db.cliente.create({ data: { nome: "Teste novo", telefone: `${tag}-novo`, email: "novo@example.invalid" } });
  await assert.rejects(() => assinar({ clienteId: clienteNovo.id, planoId: plano.id, forma: "PIX", cpf: "52998224725", origem: "SITE" }));
  const preservada = await db.assinatura.findFirst({ where: { clienteId: clienteNovo.id, status: "PENDENTE" } });
  assert(preservada);
  assert(await db.emissaoPixMensal.findFirst({ where: { assinaturaId: preservada.id, estado: "INCERTA" } }));
  const tentativas = pedidos;
  await assert.rejects(() => assinar({ clienteId: clienteNovo.id, planoId: plano.id, forma: "PIX", cpf: "52998224725", origem: "SITE" }));
  assert.equal(pedidos, tentativas);
  console.log("OK Pix concorrente, mensalidade seguinte, legado, expiração, timeout e adesão incerta");
  await db.$disconnect();
}
main().catch((e) => { console.error(e); process.exitCode = 1; });
