/** Executado somente pelo teste de entrevistas com guarda de banco descartável e rede bloqueada. */
import { processarBotEntrevista } from "@/lib/bot/entrevistas";
import { candidatoEntrevista } from "@/lib/recrutamento/entrevistas";
import { dataLocal, minutosLocal } from "@/lib/agenda/tempo";
import assert from "node:assert/strict";
import { db } from "@/lib/db";
import { configurarPiloto, reservarEnvioPiloto, reservarConvitePiloto } from "@/lib/whatsapp/piloto";
export async function testarPiloto(donoId:string, gerenteId:string, ok:(s:string)=>void,fixture:{telefone:string;entrevistaId:string;token:string;geracao:number;anteriorId:string}) {
 const telefone=fixture.telefone;
 const rejeita=(p:Promise<unknown>,status:number)=>assert.rejects(p,(e:unknown)=>!!e&&typeof e==="object"&&"status" in e&&e.status===status);
 process.env.WHATSAPP_PILOTO_ENTREVISTAS_HABILITADO="true";
 await db.pilotoEntrevistaWhatsApp.deleteMany();
 await db.configuracao.upsert({where:{id:1},create:{id:1,botAtivo:true},update:{botAtivo:true}});
 const c=await db.conversa.upsert({where:{telefone},create:{telefone,estado:"HUMANO"},update:{estado:"HUMANO"}});
 const vizinha=await db.conversa.upsert({where:{telefone:"5547999990001"},create:{telefone:"5547999990001",estado:"HUMANO"},update:{estado:"HUMANO"}});
 await rejeita(configurarPiloto(gerenteId,0,telefone),403);
 const p=await configurarPiloto(donoId,0,telefone,10);
 assert.equal(p?.ativo,true);assert.equal((await db.configuracao.findUniqueOrThrow({where:{id:1}})).botAtivo,false);
 assert.equal((await db.conversa.findUniqueOrThrow({where:{id:c.id}})).estado,"BOT");
 await rejeita(configurarPiloto(donoId,0,null),409);
 await rejeita(configurarPiloto(donoId,p!.versao,"5547999990002"),409);
 ok("piloto exige dono e versão atual, pausa IA geral e não permite trocar destino ativo");
 await rejeita(reservarEnvioPiloto(vizinha.telefone,"ENTREVISTA_PILOTO"),403);
 await rejeita(reservarEnvioPiloto(telefone,"PADRAO"),403);
 await rejeita(reservarEnvioPiloto(telefone,"TEMPLATE"),403);
 assert.equal((await db.pilotoEntrevistaWhatsApp.findUniqueOrThrow({where:{id:1}})).enviados,0);
 ok("outros destinos e finalidades não consomem tentativa nem chegam ao transporte");
 const convites=await Promise.all([reservarConvitePiloto(`${fixture.entrevistaId}:${fixture.geracao}`,p!.versao),reservarConvitePiloto(`${fixture.entrevistaId}:${fixture.geracao}`,p!.versao)]);
 assert.equal(convites.filter(Boolean).length,1);ok("convite inicial concorrente só tem uma autorização de envio");
 const ctx={conversaId:c.id,telefone};
 await db.entrevistaRecrutamento.update({where:{id:fixture.anteriorId},data:{conversaId:c.id}});
 const antiga=await processarBotEntrevista(ctx,"HORARIOS");assert.ok(antiga.resposta?.includes("somente o convite deste teste"));
 await db.entrevistaRecrutamento.update({where:{id:fixture.anteriorId},data:{conversaId:null}});
 ok("piloto não reutiliza sessão anterior nem modifica entrevista fora do convite autorizado");
 const inicio=await processarBotEntrevista(ctx,"INICIAR ENTREVISTA");assert.ok(inicio.resposta?.includes("ESCOLHER"));
 const vista=await candidatoEntrevista(fixture.token,{acao:"CONSULTAR"});
 const horario=new Date(vista.horarios[0]);const minuto=minutosLocal(horario,"America/Sao_Paulo");
 const escolha=await processarBotEntrevista(ctx,`ESCOLHER ${dataLocal(horario,"America/Sao_Paulo")} ${String(Math.floor(minuto/60)).padStart(2,"0")}:${String(minuto%60).padStart(2,"0")} ${vista.versao}`);
 assert.ok(escolha.resposta?.includes("CONFIRMAR"));
 const proposta=await candidatoEntrevista(fixture.token,{acao:"CONSULTAR"});
 assert.equal(proposta.estado,"AGUARDA_CONFIRMACAO");
 const confirmada=await processarBotEntrevista(ctx,`CONFIRMAR ${proposta.versao}`);assert.ok(confirmada.resposta?.includes("confirmada"));
 const final=await candidatoEntrevista(fixture.token,{acao:"CONSULTAR"});assert.equal(final.estado,"CONFIRMADA");
 await processarBotEntrevista(ctx,`CANCELAR ENTREVISTA ${final.versao}`);
 ok("piloto com chave geral desligada inicia, escolhe e confirma sem token no WhatsApp ou IA");
 const corrida=await Promise.allSettled(Array.from({length:41},()=>reservarEnvioPiloto(telefone,"ENTREVISTA_PILOTO")));
 assert.equal(corrida.filter(x=>x.status==="fulfilled").length,40);
 assert.equal((await db.pilotoEntrevistaWhatsApp.findUniqueOrThrow({where:{id:1}})).enviados,40);
 ok("limite de 40 tentativas é respeitado sob concorrência transacional");
 await db.pilotoEntrevistaWhatsApp.update({where:{id:1},data:{enviados:0,expiraEm:new Date(0)}});
 await rejeita(reservarEnvioPiloto(telefone,"ENTREVISTA_PILOTO"),403);
 await rejeita(reservarConvitePiloto("fixture:1",p!.versao),409);
 ok("expiração bloqueia novos convites e respostas");
 await configurarPiloto(donoId,p!.versao,null);
 assert.equal((await db.conversa.findUniqueOrThrow({where:{id:c.id}})).estado,"HUMANO");
 assert.equal((await db.conversa.findUniqueOrThrow({where:{id:vizinha.id}})).estado,"HUMANO");
 assert.equal((await db.configuracao.findUniqueOrThrow({where:{id:1}})).botAtivo,false);
 await rejeita(reservarEnvioPiloto(telefone,"ENTREVISTA_PILOTO"),403);
 await rejeita(reservarEnvioPiloto(vizinha.telefone,"PADRAO"),403);
 ok("encerrar restaura apenas a conversa alvo e mantém IA geral pausada");
 const logs=await db.auditoria.findMany({where:{entidade:"PilotoEntrevistaWhatsApp"}});
 assert.ok(!JSON.stringify(logs).includes(telefone));assert.ok(logs.some(x=>x.acao==="recrutamento.piloto.iniciar"));
 ok("auditoria registra o piloto sem expor o telefone completo");
 process.env.WHATSAPP_PILOTO_ENTREVISTAS_HABILITADO="false";
}
