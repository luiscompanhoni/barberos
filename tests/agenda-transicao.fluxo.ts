import assert from "node:assert/strict";
import { PrismaClient } from "@prisma/client";
import { criarAgendamento } from "../src/lib/agenda/agendamentos";
import { cancelarPeloCliente, remarcarPeloCliente } from "../src/lib/agenda/cliente";
import { salvarConfiguracaoOperacional } from "../src/lib/agenda/configuracao-operacional";
import { checarTransicaoNaReserva } from "../src/lib/agenda/transicao";
import { horariosDisponiveis } from "../src/lib/agenda/consultas";
import { dataLocal } from "../src/lib/agenda/tempo";
import { executarFerramenta } from "../src/lib/bot/ferramentas";

const url = new URL(process.env.DATABASE_URL ?? "");
if (url.hostname !== "127.0.0.1" || url.port !== "15439" || url.pathname !== "/barberos_test_agenda_transicao") throw new Error("Somente banco de teste isolado da transição.");
const db = new PrismaClient();
const sufixo = String(Date.now());
async function main() {
  const dono = await db.usuario.upsert({ where: { telefone: "5511900000101" }, create: { telefone: "5511900000101", nome: "Dono de teste", papel: "DONO" }, update: {} });
  const usuario = await db.usuario.create({ data: { telefone: `5511${sufixo.slice(-9)}`, nome: "Barbeiro de teste", papel: "BARBEIRO" } });
  const barbeiro = await db.barbeiro.create({ data: { usuarioId: usuario.id, nome: "Teste transição" } });
  const cliente = await db.cliente.create({ data: { telefone: `5521${sufixo.slice(-9)}`, nome: "Cliente sintético" } });
  const servico = await db.servico.create({ data: { nome: "Corte de teste", duracaoMin: 30, precoCentavos: 6500, barbeiros: { create: { barbeiroId: barbeiro.id } } } });
  const s = { usuarioId: dono.id, papel: "DONO" as const, nome: dono.nome, barbeiroId: null, clienteId: null };
  const inicio = new Date(Date.now() + 3 * 86_400_000);
  const ag = await db.agendamento.create({ data: { barbeiroId: barbeiro.id, clienteId: cliente.id, servicoId: servico.id, inicio, fim: new Date(+inicio + 1_800_000), precoCentavos: 6500, origem: "SITE" } });
  const contexto = await db.conversa.create({ data: { telefone: `5531${sufixo.slice(-9)}`, estado: "BOT" } });
  await db.configuracao.upsert({ where: { id: 1 }, create: { id: 1 }, update: { agendaExternaAtiva: false } });
  await db.$transaction(tx => checarTransicaoNaReserva(tx));
  await assert.rejects(salvarConfiguracaoOperacional({ ...s, papel: "BARBEIRO" }, { tipo: "fonte", agendaExternaAtiva: true }), { status: 403 });
  await salvarConfiguracaoOperacional(s, { tipo: "fonte", agendaExternaAtiva: true });
  const recusado = { codigo: "confirmacao_equipe" };
  await assert.rejects(horariosDisponiveis({ data: dataLocal(inicio), servicoId: servico.id, paraCliente: true }), recusado);
  await assert.rejects(criarAgendamento({ barbeiroId: barbeiro.id, servicoId: servico.id, inicio: new Date(+inicio + 3_600_000), cliente: { id: cliente.id }, origem: "SITE" }, null), recusado);
  await assert.rejects(remarcarPeloCliente(cliente.id, ag.id, new Date(+inicio + 3_600_000)), recusado);
  await assert.rejects(cancelarPeloCliente(cliente.id, ag.id), recusado);
  const intocado = await db.agendamento.findUniqueOrThrow({ where: { id: ag.id } });
  assert.equal(intocado.status, "MARCADO"); assert.equal(+intocado.inicio, +inicio);
  assert.equal(await db.agendamento.count({ where: { clienteId: cliente.id } }), 1);
  const r = await executarFerramenta("consultar_horarios", { data: dataLocal(inicio), servico_id: servico.id }, { conversaId: contexto.id, telefone: contexto.telefone, nomePerfil: null });
  assert.equal(r.passouParaHumano, true);
  assert.equal((await db.conversa.findUniqueOrThrow({ where: { id: contexto.id } })).estado, "HUMANO");
  assert.equal(await db.mensagem.count({ where: { conversaId: contexto.id, autor: "NOTA" } }), 1);
  assert.equal(await db.mensagem.count({ where: { conversaId: contexto.id, autor: { not: "NOTA" } } }), 0);
  await salvarConfiguracaoOperacional(s, { tipo: "fonte", agendaExternaAtiva: false });
  await db.$transaction(tx => checarTransicaoNaReserva(tx));

  let iniciou!: () => void, liberar!: () => void;
  const comecou = new Promise<void>(r => { iniciou = r; });
  const espera = new Promise<void>(r => { liberar = r; });
  const reserva = db.$transaction(async tx => { await checarTransicaoNaReserva(tx); iniciou(); await espera; });
  await comecou;
  let terminou = false;
  const mudanca = salvarConfiguracaoOperacional(s, { tipo: "fonte", agendaExternaAtiva: true }).then(() => { terminou = true; });
  await new Promise(r => setTimeout(r, 100));
  assert.equal(terminou, false, "a ativação aguarda a confirmação que já segurava a trava");
  liberar(); await Promise.all([reserva, mudanca]);
  await assert.rejects(db.$transaction(tx => checarTransicaoNaReserva(tx)), recusado);
  await salvarConfiguracaoOperacional(s, { tipo: "fonte", agendaExternaAtiva: false });
  console.log(JSON.stringify({ bancoIsolado: true, disponiblidadeBloqueada: true, criacaoBloqueada: true, remarcacaoBloqueada: true, cancelamentoBloqueado: true, registrosPreservados: true, botEncaminhado: true, nenhumaMensagemEnviada: true, ativacaoSerializada: true, donoObrigatorio: true }));
}
main().finally(() => db.$disconnect());
